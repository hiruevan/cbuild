
function Invoke-CBuildResources {
    param(
        [Parameter(Mandatory)][hashtable]$Cfg,
        [Parameter(Mandatory)][string]$OutDir
    )

    $platDir = Join-Path $PWD.Path $OutDir
    $genDir  = Join-Path $platDir "resources"

    $spriteCompiler = Join-Path $script:CBuildInstallDir "python\compilespritefolder.py"
    $inputCompiler  = Join-Path $script:CBuildInstallDir "python\generateinputs.py"

    New-Item -ItemType Directory -Path $platDir -Force | Out-Null
    New-Item -ItemType Directory -Path $genDir -Force | Out-Null

    $headers = @()
    $resPath = Join-Path $PWD.Path $Cfg.RESOURCES

    # Get Python when needed.
    $python = $script:CBuildPython

    if (-not $python) {
        $python = Get-CBuildPython
    }

    # ============================================================
    # Input generation
    # ============================================================

    $platform = Split-Path $OutDir -Leaf

    $inputHeader = Join-Path $platDir "input.h"
    $inputSource = Join-Path $platDir "input.c"

    if ($Cfg.KEYBINDS) {
        # Keybind configuration is normally inside RESOURCES.
        $keybindPath = Join-Path $resPath $Cfg.KEYBINDS

        # Also support configurations relative to the project root.
        if (-not (Test-Path -LiteralPath $keybindPath -PathType Leaf)) {
            $keybindPath = Join-Path $PWD.Path $Cfg.KEYBINDS
        }

        if (-not (Test-Path -LiteralPath $keybindPath -PathType Leaf)) {
            throw "Keybind configuration not found: $keybindPath"
        }

        if (-not $python) {
            throw "Python is unavailable. Run 'cbuild install' again."
        }

        Write-Host "    inputs: $platform (input.h, input.c)"

        & $python.Path @($python.Args) $inputCompiler $keybindPath $platDir $platform

        if ($LASTEXITCODE -ne 0) {
            throw "Input generation failed for platform '$platform'."
        }

        # Verify that both generated files exist.
        if (-not (Test-Path -LiteralPath $inputHeader -PathType Leaf)) {
            throw "Input generation did not create input.h for '$platform'."
        }

        if (-not (Test-Path -LiteralPath $inputSource -PathType Leaf)) {
            throw "Input generation did not create input.c for '$platform'."
        }
    }
    else {
        # Ensure input files always exist, even without keybinds.
        Write-Host "    inputs: $platform (default input.h, input.c)"

        $headerText = @(
            "// Generated by cbuild. No keybind configuration."
            "#pragma once"
        ) -join "`n"

        $sourceText = @(
            "// Generated by cbuild. No keybind configuration."
            '#include "input.h"'
        ) -join "`n"

        [System.IO.File]::WriteAllText(
            $inputHeader,
            "$headerText`n",
            (New-Object System.Text.UTF8Encoding $false)
        )

        [System.IO.File]::WriteAllText(
            $inputSource,
            "$sourceText`n",
            (New-Object System.Text.UTF8Encoding $false)
        )
    }

    # ============================================================
    # Resource generation
    # ============================================================

    if (Test-Path -LiteralPath $resPath -PathType Container) {
        $resRoot = (Resolve-Path -LiteralPath $resPath).ProviderPath.TrimEnd('\')

        # --- .sprite files ---
        $groups = Get-ChildItem -LiteralPath $resRoot -Recurse -File -Filter *.sprite |
            Group-Object DirectoryName |
            Sort-Object Name

        foreach ($g in $groups) {
            $rel = $g.Name.Substring($resRoot.Length).Trim('\', '/')
            $prefix = $rel -replace '[\\/]+', '_'

            $hdr = if ($prefix) {
                "res_$prefix.h"
            }
            else {
                "res_root.h"
            }

            if (-not $python) {
                throw "Python is unavailable. Run 'cbuild install' again."
            }

            Write-Host "    sprites: $(if ($rel) { $rel } else { '(root)' }) ($hdr)"

            & $python.Path @($python.Args) $spriteCompiler `
                $g.Name `
                (Join-Path $genDir $hdr) `
                $prefix | Out-Null

            if ($LASTEXITCODE -ne 0) {
                throw "Sprite compile failed for $($g.Name)."
            }

            $headers += $hdr
        }
    }

    # ============================================================
    # Cleanup generated resource headers
    # ============================================================

    Get-ChildItem -LiteralPath $genDir -Filter *.h -File |
        Where-Object { $headers -notcontains $_.Name } |
        Remove-Item -Force

    # ============================================================
    # resources.h generation
    # ============================================================

    $lines = @(
        "// Generated by cbuild. Do not edit."
        "#pragma once"
    ) + (
        $headers | ForEach-Object {
            "#include `"resources/$_`""
        }
    )

    $text = ($lines -join "`n") + "`n"
    $dest = Join-Path $platDir "resources.h"

    if (
        -not (Test-Path -LiteralPath $dest) -or
        (Get-Content -LiteralPath $dest -Raw) -ne $text
    ) {
        [System.IO.File]::WriteAllText(
            $dest,
            $text,
            (New-Object System.Text.UTF8Encoding $false)
        )
    }
}
